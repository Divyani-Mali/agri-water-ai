"""Temporary in-memory registry for TTS audio blobs.

Purpose
-------
When a client calls ``POST /api/chat/speech?mode=url`` the endpoint cannot
stream the audio inline (the client needs a URL to hand to an <audio> element).
In that case the generated bytes are held here under a random token and the
endpoint returns that token as an ``audio_id``.  The client then fetches
``GET /api/chat/audio/{audio_id}`` to retrieve the bytes.

Design constraints
------------------
*   Audio is NEVER written to disk in URL mode — the bytes live only in this
    in-process dict.  This avoids any file-system permission or cleanup issues.
*   Each entry carries the owner's user_id so the retrieval endpoint can verify
    that only the same user may download their audio.
*   Entries expire after ``AUDIO_RETENTION_MINUTES`` minutes.  The ``evict()``
    function is called on every read and by the background lifespan task so
    stale entries do not accumulate.
*   Because the store is in-process it resets on server restart — consistent
    with the existing in-memory rate-limit design in chat_service.py.
"""
from __future__ import annotations

import secrets
import threading
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone


@dataclass
class _Entry:
    user_id: int
    audio_bytes: bytes
    mime_type: str
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))


_lock = threading.Lock()
_store: dict[str, _Entry] = {}


def put(user_id: int, audio_bytes: bytes, mime_type: str) -> str:
    """Store *audio_bytes* and return a random opaque audio_id."""
    audio_id = secrets.token_urlsafe(32)
    with _lock:
        _store[audio_id] = _Entry(
            user_id=user_id,
            audio_bytes=audio_bytes,
            mime_type=mime_type,
        )
    return audio_id


def get(audio_id: str, user_id: int, retention_minutes: int) -> tuple[bytes, str] | None:
    """Return ``(audio_bytes, mime_type)`` if the entry exists, is owned by
    *user_id*, and has not expired.  Returns ``None`` otherwise.

    The entry is removed immediately after a successful read (single-use).
    """
    evict(retention_minutes)
    with _lock:
        entry = _store.get(audio_id)
        if entry is None:
            return None
        if entry.user_id != user_id:
            # Wrong owner — treat as not-found (don't leak existence)
            return None
        del _store[audio_id]
        return entry.audio_bytes, entry.mime_type


def evict(retention_minutes: int) -> int:
    """Remove entries older than *retention_minutes*.  Returns the number evicted."""
    cutoff = datetime.now(timezone.utc) - timedelta(minutes=retention_minutes)
    with _lock:
        stale = [k for k, v in _store.items() if v.created_at < cutoff]
        for k in stale:
            del _store[k]
    return len(stale)


def clear() -> None:
    """Remove all entries.  Used in tests to reset state between cases."""
    with _lock:
        _store.clear()


def size() -> int:
    """Current number of stored entries (for tests / monitoring)."""
    with _lock:
        return len(_store)
